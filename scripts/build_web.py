"""Export Betty's rules and tables for the web app (docs/betty-data.js).

The Python package is the single source of truth: word lists, E-numbers, diet
labels, category shortcuts and score tables are copied from it, so the website
and the command line always agree (tests/test_web_parity.py checks this).

    python scripts/build_web.py          # rebuild docs/betty-data.js

Additive risk levels come from data/additive_overrides.json plus the Open Food
Facts additives taxonomy (ODbL), the same way the CLI computes them.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from betty import __version__, diet, score, categories, off, cli, additives  # noqa: E402

OUT = os.path.join(ROOT, "docs", "betty-data.js")
RULE_NAMES = ["PORK", "BEEF", "ALCOHOL", "DOUBTFUL_WORDS", "DOUBTFUL_OK", "CHECK_WORDS", "ANIMAL_DERIVED",
              "VEG_RENNET_OK", "FISH_DERIVED_OK", "MEAT", "FISH", "SHELLFISH", "GLUTEN_WORDS", "OATS", "SUGARS",
              "DAIRY_WORDS", "PLANT_MILKS", "VINEGARS", "GLYCERIN", "GF_WORD", "DOUBTFUL_E", "ANIMAL_E", "HARAM_E",
              "ALLERGEN", "GLUTEN_FREE_LABELS", "LACTOSE_FREE_LABELS"]


def _plain(v):
    if isinstance(v, (set, frozenset)):
        return sorted(v)
    if isinstance(v, (list, tuple)):
        return [_plain(x) for x in v]
    if isinstance(v, dict):
        return {str(k): _plain(x) for k, x in v.items()}
    return v


def additive_levels() -> dict:
    codes = set(additives.overrides())
    codes |= {k.split(":", 1)[1] for k in additives.taxonomy() if k.startswith("en:e")}
    out = {}
    for c in sorted(codes):
        lvl = additives.risk(c)
        if lvl != "unknown":
            out[c] = lvl
    return out


def build(with_additives=True) -> dict:
    data = {
        "version": __version__,
        "solid": _plain(score.SOLID), "liquid": _plain(score.LIQUID),
        "additive_cost": score.ADDITIVE_COST, "bands": _plain(score.BANDS),
        "rules": {n: _plain(getattr(diet, n)) for n in RULE_NAMES},
        "diets": [[k, label, badge] for k, (label, _test, badge) in diet.DIETS.items()],
        "shortcuts": categories.SHORTCUTS, "generic": sorted(cli.GENERIC),
        "beverage_cats": sorted(off.BEVERAGE_CATS), "not_beverage": sorted(off.NOT_BEVERAGE),
        "organic_labels": list(off.ORGANIC_LABELS), "fields": off.FIELDS,
    }
    if with_additives:
        data["additives"] = additive_levels()
    return data


def main():
    data = build()
    js = ("// Generated by scripts/build_web.py from the Python package. Do not edit by hand.\n"
          "// Additive levels derive from the Open Food Facts additives taxonomy (ODbL) and\n"
          "// betty/data/additive_overrides.json.\n"
          "window.BETTY_DATA = " + json.dumps(data, ensure_ascii=False, indent=0, sort_keys=True) + ";\n")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(js)
    print(f"wrote {OUT} ({len(js) // 1024} KB, {len(data['additives'])} additives)")


if __name__ == "__main__":
    main()
